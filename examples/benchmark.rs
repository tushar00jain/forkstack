use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant};

use forkstack::core::submit::{self, SubmitOptions};
use forkstack::ui::git::load_graph_for;
use git2::{Oid, Repository, Signature};

const SAMPLES: usize = 5;
const RELEVANT_SIZES: [usize; 4] = [5, 25, 50, 100];
const UNRELATED_SIZES: [usize; 4] = [0, 25, 50, 100];
const MARKER: &str = ".forkstack-benchmark";

struct FixtureRoot(PathBuf);

impl FixtureRoot {
    fn create() -> Result<Self, String> {
        let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("target")
            .join("forkstack-benchmark");
        if path.exists() {
            if !path.join(MARKER).is_file() {
                return Err(format!(
                    "refusing to remove {}: benchmark marker is missing",
                    path.display()
                ));
            }
            fs::remove_dir_all(&path).map_err(|error| error.to_string())?;
        }
        fs::create_dir_all(&path).map_err(|error| error.to_string())?;
        if let Err(error) = fs::write(path.join(MARKER), "generated by the forkstack benchmark\n") {
            let _ = fs::remove_dir(&path);
            return Err(error.to_string());
        }
        Ok(Self(path))
    }
}

impl Drop for FixtureRoot {
    fn drop(&mut self) {
        if !self.0.join(MARKER).is_file() {
            eprintln!(
                "warning: refusing to remove {}: benchmark marker is missing",
                self.0.display()
            );
            return;
        }
        if let Err(error) = fs::remove_dir_all(&self.0) {
            eprintln!("warning: could not remove {}: {error}", self.0.display());
        }
    }
}

struct Fixture {
    repo: Repository,
    path: PathBuf,
    base: Oid,
}

impl Fixture {
    fn create(path: PathBuf) -> Result<Self, String> {
        let repo = Repository::init(&path).map_err(git_error)?;
        repo.remote("origin", "git@github.com:benchmark/forkstack.git")
            .map_err(git_error)?;
        let base = commit(&repo, Some("refs/remotes/origin/main"), None, "base")?;
        Ok(Self { repo, path, base })
    }

    fn relevant_stack(&self, count: usize) -> Result<Vec<Oid>, String> {
        let mut commits = Vec::with_capacity(count);
        let mut parent = self.base;
        for number in 1..=count {
            let message = format!("relevant {number}\n\nfs-branch: benchmark/{number}\n");
            parent = commit(&self.repo, None, Some(parent), &message)?;
            commits.push(parent);
        }
        Ok(commits)
    }

    fn point_head(&self, target: Oid) -> Result<(), String> {
        self.repo
            .reference("refs/heads/benchmark", target, true, "benchmark case")
            .map_err(git_error)?;
        self.repo
            .set_head("refs/heads/benchmark")
            .map_err(git_error)
    }

    fn add_unrelated(&self, first: usize, last: usize) -> Result<(), String> {
        for number in first..=last {
            commit(
                &self.repo,
                Some(&format!("refs/heads/unrelated/{number}")),
                None,
                &format!("unrelated {number}"),
            )?;
        }
        Ok(())
    }
}

fn git_error(error: git2::Error) -> String {
    error.message().to_owned()
}

fn commit(
    repo: &Repository,
    update_ref: Option<&str>,
    parent: Option<Oid>,
    message: &str,
) -> Result<Oid, String> {
    let tree_oid = {
        let builder = repo.treebuilder(None).map_err(git_error)?;
        builder.write().map_err(git_error)?
    };
    let tree = repo.find_tree(tree_oid).map_err(git_error)?;
    let signature =
        Signature::now("Forkstack Benchmark", "benchmark@example.invalid").map_err(git_error)?;
    let parent = parent
        .map(|oid| repo.find_commit(oid).map_err(git_error))
        .transpose()?;
    let parents: Vec<_> = parent.iter().collect();
    repo.commit(update_ref, &signature, &signature, message, &tree, &parents)
        .map_err(git_error)
}

#[derive(Clone, Copy)]
struct Measurement {
    plan: Duration,
    graph: Duration,
    preview: Duration,
    commits: usize,
    nodes: usize,
}

fn measure(path: &Path) -> Result<Measurement, String> {
    let options = SubmitOptions {
        repo: path.to_owned(),
        remote: "origin".into(),
        base: "main".into(),
        prefix: None,
        draft: true,
    };
    let start = Instant::now();
    let plan = submit::plan(options)?;
    let after_plan = Instant::now();
    let graph = load_graph_for(path, "origin", "main")?;
    let after_graph = Instant::now();
    let preview = graph.publish_preview(&plan)?;
    let end = Instant::now();
    Ok(Measurement {
        plan: after_plan - start,
        graph: after_graph - after_plan,
        preview: end - after_graph,
        commits: plan.commits.len(),
        nodes: preview.commits.len(),
    })
}

fn median_measurement(path: &Path) -> Result<Measurement, String> {
    // Warm filesystem and allocator state once, outside the reported samples.
    let _ = measure(path)?;
    let mut samples = (0..SAMPLES)
        .map(|_| measure(path))
        .collect::<Result<Vec<_>, _>>()?;
    samples.sort_by_key(|sample| sample.plan + sample.graph + sample.preview);
    Ok(samples[SAMPLES / 2])
}

fn micros(duration: Duration) -> u128 {
    duration.as_micros()
}

fn peak_rss_kib() -> Option<u64> {
    let status = fs::read_to_string("/proc/self/status").ok()?;
    status.lines().find_map(|line| {
        line.strip_prefix("VmHWM:")?
            .split_whitespace()
            .next()?
            .parse()
            .ok()
    })
}

fn print_header() {
    println!(
        "case,relevant,unrelated,plan_us,graph_us,preview_us,total_us,displayed_graph_nodes,expected_subprocesses,peak_rss_kib"
    );
}

fn print_measurement(label: &str, unrelated: usize, sample: Measurement) {
    let total = sample.plan + sample.graph + sample.preview;
    let peak = peak_rss_kib()
        .map(|value| value.to_string())
        .unwrap_or_else(|| "n/a".into());
    println!(
        "{label},{},{unrelated},{},{},{},{},{},0,{peak}",
        sample.commits,
        micros(sample.plan),
        micros(sample.graph),
        micros(sample.preview),
        micros(total),
        sample.nodes,
    );
}

fn run() -> Result<(), String> {
    let root = FixtureRoot::create()?;
    println!("forkstack f-preview benchmark (median of {SAMPLES} samples)");
    println!("fixtures: {} (removed on exit)", root.0.display());
    println!(
        "displayed_graph_nodes counts nodes retained for display, not all refs or objects inspected"
    );
    println!(
        "expected_subprocesses is 0 because these code paths use git2; process creation is not instrumented"
    );
    print_header();

    let relevant = Fixture::create(root.0.join("relevant"))?;
    let commits = relevant.relevant_stack(*RELEVANT_SIZES.last().unwrap())?;
    for size in RELEVANT_SIZES {
        relevant.point_head(commits[size - 1])?;
        print_measurement("relevant", 0, median_measurement(&relevant.path)?);
    }

    let unrelated = Fixture::create(root.0.join("unrelated"))?;
    let stack = unrelated.relevant_stack(5)?;
    unrelated.point_head(*stack.last().unwrap())?;
    let mut previous = 0;
    for count in UNRELATED_SIZES {
        if count > previous {
            unrelated.add_unrelated(previous + 1, count)?;
        }
        print_measurement("unrelated", count, median_measurement(&unrelated.path)?);
        previous = count;
    }
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("benchmark failed: {error}");
        std::process::exit(1);
    }
}
